import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-angle=metal','--enable-gpu','--ignore-gpu-blocklist']});
const context=await browser.newContext({viewport:{width:900,height:760},deviceScaleFactor:1});
const page=await context.newPage();
page.setDefaultTimeout(60000);
const ROOT=process.env.GAME_URL || 'http://localhost:5262/';
await fs.mkdir('docs/qa/campaign/production',{recursive:true});
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
const state=async()=>JSON.parse(await page.evaluate(()=>window.render_game_to_text()));
try {
 await page.goto(ROOT,{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>window.render_game_to_text);
 assert.equal((await state()).mission.level,1);
 assert.equal(await page.locator('#grade').count(),0);
 assert.equal(await page.locator('#start').isVisible(),true);
 await page.screenshot({path:'docs/qa/campaign/production/900-initial.png'});
 await page.locator('#levels').click();
 assert.equal(await page.locator('[data-level]').count(),30);
 assert.equal(await page.locator('[data-level]:disabled').count(),29);
 assert.equal(await page.locator('[data-level="1"]').evaluate(el=>document.activeElement===el),true);
 await page.keyboard.press('Shift+Tab');
 assert.equal(await page.locator('#close-levels').evaluate(el=>document.activeElement===el),true);
 await page.keyboard.press('Shift+Tab');
 assert.equal(await page.locator('#close-levels-bottom').evaluate(el=>document.activeElement===el),true);
 await page.screenshot({path:'docs/qa/campaign/production/900-map.png'});
 await page.locator('#close-levels').click();
 await page.locator('#start').click();
 await page.locator('#read-mode').click();
 await page.keyboard.press('Digit2');
 assert.equal((await state()).manual.reading,true,'inactive shortcut keeps reading mode');
 await page.locator('#operate').click();
 assert.equal((await state()).selected,'valves','inactive cable keyboard selection must be ignored');
 await page.locator('#controls-toggle').click();
 await page.locator('[data-control="small"]').click();
 assert.equal((await state()).mode,'ready');
 assert.equal((await state()).campaign.highestUnlocked,1);
 await page.locator('#engine-start').click();
 assert.equal((await state()).campaign.highestUnlocked,2);
 await page.screenshot({path:'docs/qa/campaign/production/900-first-win.png'});
 await page.locator('#next').click();
 assert.equal((await state()).mission.level,2);
 assert.equal((await state()).manual.page,'cable');
 assert.equal((await state()).audio.moduleStems,0);
 await page.reload({waitUntil:'domcontentloaded'});
 assert.equal((await state()).mission.level,2);
 await page.locator('#levels').click();
 await page.locator('[data-level="1"]').click();
 assert.equal((await state()).mission.level,1);
 assert.equal((await state()).campaign.highestUnlocked,2);
 assert.equal(await page.locator('[data-page]').count(),1);
 await page.screenshot({path:'docs/qa/campaign/production/900-replay.png'});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'docs/qa/campaign/production/390-initial.png'});
 await page.locator('#levels').click();
 await page.screenshot({path:'docs/qa/campaign/production/390-map.png'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
 const close=await page.locator('#close-levels-bottom').boundingBox();
 assert.ok(close.y+close.height<=844);
 await page.goto(new URL('?manual=1',ROOT).href,{waitUntil:'domcontentloaded'});
 assert.equal(await page.locator('.manual-mission').count(),30);
 await page.locator('#reader-level').selectOption('30');
 const finalManual=await page.locator('#manual-level-30').boundingBox();
 assert.ok(finalManual.y >= 0 && finalManual.y < 400,'partner level jump locates final manual');
 assert.doesNotMatch(await page.locator('.reader').innerText(),/GRADE|כיתה/);
 assert.deepEqual(errors,[]);
 await fs.writeFile('docs/qa/campaign/production/smoke-results.json',JSON.stringify({checks:['no grade selector','30 sequentially locked levels','first active-only win','unlock requires engine start','next level correct manual','reload resume','unlocked replay','390 map bounds','keyboard map focus loop','inactive keyboard module ignored','partner30 direct jump'],errors},null,2));
 console.log('Campaign smoke passed');
}finally{await browser.close();}
